"""The voice harvester — extraction law + backfill CLI path.

The extraction law, verified against real transcripts 2026-08-13: KEEP a record iff
type=="user" AND
message.role=="user" AND message.content is a STRING AND isMeta is not true AND
isSidechain is not true AND userType=="external", minus belt-and-suspenders content
excludes (command wrappers, system-reminders, interrupted markers, empty).

All fixture records below are SYNTHETIC — structurally shaped like real Claude Code
transcript records (field names verified against real files, values invented). No real
transcript is ever read by this suite.
"""
