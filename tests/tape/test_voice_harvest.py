def test_cmd_harvest_summary_counts_and_exit_code(tmp_path):
    db = tmp_path / "tape.db"
    transcripts = tmp_path / "transcripts"
    _write_jsonl(transcripts / "session1.jsonl", [
        _user_record("first kept prompt"),
        _user_record("tool result", isMeta=True),          # dropped by law, not counted
        _user_record([{"type": "tool_result"}]),            # dropped by law, not counted
        "{not valid json at all",                            # malformed
        _user_record("second kept prompt", timestamp="2026-08-01T12:05:00.000Z"),
    ])

    tape = Tape(db)
    rc = voice.cmd_harvest(_harvest_args(transcripts), tape)

    assert rc == 0
    rows = tape._conn.execute("SELECT text, source, register, session FROM voice ORDER BY id").fetchall()
    assert [r[0] for r in rows] == ["first kept prompt", "second kept prompt"]
    assert rows[0][1] == "session1"                    # source = filename stem
    assert rows[0][2] == "chat"                         # register = args.register
    assert rows[0][3] == "sess-synthetic-A"              # session = sessionId field


