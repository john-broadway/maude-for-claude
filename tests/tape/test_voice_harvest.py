# --- fixture builders (synthetic, shape-only) -----------------------------------------

def _user_record(content, **overrides):
    """A minimally-valid KEPT record shape. Override any top-level or message field."""
    message = {"role": overrides.pop("role", "user"), "content": content}
    rec = {
        "type": overrides.pop("type", "user"),
        "isMeta": overrides.pop("isMeta", False),
        "isSidechain": overrides.pop("isSidechain", False),
        "userType": overrides.pop("userType", "external"),
        "message": message,
        "timestamp": overrides.pop("timestamp", "2026-08-01T12:00:00.000Z"),
        "sessionId": overrides.pop("sessionId", "sess-synthetic-A"),
    }
    rec.update(overrides)
    return rec


def _write_jsonl(path: pathlib.Path, lines: list) -> None:
    """Write raw lines (dicts are json.dumps'd, strings written verbatim — for
    planting malformed JSON on purpose)."""
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", encoding="utf-8") as fh:
        for line in lines:
            if isinstance(line, str):
                fh.write(line + "\n")
            else:
                fh.write(json.dumps(line) + "\n")


def _harvest_args(transcripts, register="chat"):
    return SimpleNamespace(transcripts=str(transcripts), register=register)


