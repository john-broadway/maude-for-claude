def test_cmd_harvest_dedupes_across_two_files_with_the_identical_record(tmp_path):
    """DOUBLE-COUNT LAW: a resumed/forked session copies history into a NEW transcript
    file with the SAME original timestamp. sha keys on text+original-ts only, so the
    copy collapses via INSERT OR IGNORE regardless of which file or session carried it."""
    db = tmp_path / "tape.db"
    transcripts = tmp_path / "transcripts"
    shared = _user_record("resumed session repeats this line",
                           timestamp="2026-08-01T09:00:00.000Z", sessionId="sess-original")
    resumed_copy = _user_record("resumed session repeats this line",
                                 timestamp="2026-08-01T09:00:00.000Z", sessionId="sess-resumed")
    _write_jsonl(transcripts / "original.jsonl", [shared])
    _write_jsonl(transcripts / "resumed-copy.jsonl", [resumed_copy])

    tape = Tape(db)
    voice.cmd_harvest(_harvest_args(transcripts), tape)

    (count,) = tape._conn.execute("SELECT COUNT(*) FROM voice").fetchone()
    assert count == 1


