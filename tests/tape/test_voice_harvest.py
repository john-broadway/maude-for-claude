def test_cmd_harvest_skips_an_unreadable_file_without_crashing_and_keeps_going(tmp_path, capsys):
    """A dangling symlink named *.jsonl raises OSError on open() regardless of chmod (this
    box runs as root, which bypasses permission bits) — a reliable, permission-independent
    way to prove one unopenable file among 2,101 real ones does not abort the whole harvest."""
    db = tmp_path / "tape.db"
    transcripts = tmp_path / "transcripts"
    transcripts.mkdir(parents=True)
    _write_jsonl(transcripts / "good.jsonl", [_user_record("survives the broken sibling")])
    (transcripts / "broken.jsonl").symlink_to(transcripts / "does-not-exist.jsonl")

    tape = Tape(db)
    rc = voice.cmd_harvest(_harvest_args(transcripts), tape)

    assert rc == 0
    out, err = capsys.readouterr()
    assert "files=1" in out          # the unreadable one is not counted as a file harvested
    assert "broken.jsonl" in err     # but its failure IS logged, not swallowed silently
    rows = [r[0] for r in tape._conn.execute("SELECT text FROM voice").fetchall()]
    assert rows == ["survives the broken sibling"]


class _CommitCounter:
    """Wraps a real sqlite3.Connection to count commit() calls. sqlite3.Connection is a
    C-level object — its methods can't be monkeypatched in place — so this proxies
    everything else straight through and swaps in for tape._conn (an ordinary, freely
    reassignable Python attribute)."""

    def __init__(self, conn):
        self._real = conn
        self.commits = 0

    def commit(self):
        self.commits += 1
        self._real.commit()

    def __getattr__(self, name):
        return getattr(self._real, name)


def test_cmd_harvest_commits_per_file_not_per_row(tmp_path):
    """Committing after every inserted row would mean an fsync per kept prompt across a
    2,101-file backfill. Commit granularity is per FILE: spy on the connection's commit
    count across two files worth of multiple kept rows and confirm it stays small."""
    db = tmp_path / "tape.db"
    transcripts = tmp_path / "transcripts"
    _write_jsonl(transcripts / "a.jsonl", [
        _user_record("a-one"),
        _user_record("a-two", timestamp="2026-08-01T12:01:00.000Z"),
        _user_record("a-three", timestamp="2026-08-01T12:02:00.000Z"),
    ])
    _write_jsonl(transcripts / "b.jsonl", [
        _user_record("b-one", timestamp="2026-08-01T13:00:00.000Z"),
        _user_record("b-two", timestamp="2026-08-01T13:01:00.000Z"),
    ])

    tape = Tape(db)
    counter = _CommitCounter(tape._conn)
    tape._conn = counter

    voice.cmd_harvest(_harvest_args(transcripts), tape)

    assert counter.commits == 2, "expected one commit per file (2 files), not one per row (5 rows)"
    (count,) = tape._conn.execute("SELECT COUNT(*) FROM voice").fetchone()
    assert count == 5


def test_cmd_harvest_end_to_end_via_the_real_cli(tmp_path):
    """Proves the __main__.py wiring is real, not just the module-level function."""
    import subprocess

    root = pathlib.Path(__file__).resolve().parents[2]
    db = tmp_path / "tape.db"
    transcripts = tmp_path / "transcripts"
    _write_jsonl(transcripts / "s.jsonl", [_user_record("end to end via the cli")])

    r = subprocess.run(
        [sys.executable, "-m", "maude_tape", "harvest",
         "--db", str(db), "--transcripts", str(transcripts)],
        cwd=root, capture_output=True, text=True,
    )
    assert r.returncode == 0
    assert "kept=1" in r.stdout

    tape = Tape(db)
    (count,) = tape._conn.execute("SELECT COUNT(*) FROM voice").fetchone()
    assert count == 1
